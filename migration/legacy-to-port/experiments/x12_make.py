"""Generate x12_roc_one_obs.sas: the standard error of PROC LOGISTIC's ROC area when a class has ONE
observation whose component differs from the area (tied for the area within ROCEPS, different for the
standard error): X07 groups 91, 92 print 6.1e-78 where 'a class of one adds nothing' gives 0.
  A  one event, one non-event, d apart (d from below the standard error's tolerance to above ROCEPS),
     several bases, event above and below
  B  one event and k non-events (and mirrored), the event tied for the area with one of them
  C  controls: classes of two with the same tie; one-observation classes whose component IS the area
Usage: python3 x12_make.py > x12_roc_one_obs.sas   (x12_groups.json is written next to it)"""

import json
import struct
from pathlib import Path


def hx(x: float) -> str:
    return struct.pack(">d", x).hex().upper()


groups: list[dict] = []


def add(tag: str, rows: list[tuple[float, int]], part: str) -> None:
    groups.append({"g": len(groups) + 1, "part": part, "tag": tag, "rows": [[hx(p), y] for p, y in rows]})


def mirror(rows: list[tuple[float, int]]) -> list[tuple[float, int]]:
    return [(p, 1 - y) for p, y in rows]


DS = (5e-14, 1.2e-13, 2e-13, 1e-12, 1e-10, 1e-9, 1.02e-8, 1.05e-8, 1.06e-8, 2e-8, 1e-6)
for base in (0.5, 0.3, 0.9, 0.001, 0.0):
    for d in DS:
        add(f"one_one_up_{base}_{d:.4g}", [(base, 0), (base + d, 1)], "A")
        add(f"one_one_down_{base}_{d:.4g}", [(base + d, 0), (base, 1)], "A")
for d in (1e-12, 1e-9):
    for k, others in ((2, [0.2]), (3, [0.2, 0.1]), (5, [0.2, 0.1, 0.05, 0.7]), (3, [0.7, 0.8]), (9, [0.2, 0.1, 0.05, 0.7, 0.75, 0.8, 0.85, 0.9])):
        rows = [(0.5, 0), (0.5 + d, 1), *[(o, 0) for o in others]]
        add(f"one_event_{k}_nonevents_{d:.4g}", rows, "B")
        add(f"one_nonevent_{k}_events_{d:.4g}", mirror(rows), "B")
        add(f"one_event_below_{k}_nonevents_{d:.4g}", [(0.5 + d, 0), (0.5, 1), *[(o, 0) for o in others]], "B")
    # the lone event inside a chain of three values, each within ROCEPS of the largest
    add(f"chain_event_top_{d:.4g}", [(0.5, 0), (0.5 + d, 0), (0.5 + 2 * d, 1)], "B")
    add(f"chain_event_mid_{d:.4g}", [(0.5, 0), (0.5 + d, 1), (0.5 + 2 * d, 0)], "B")
    add(f"chain_event_low_{d:.4g}", [(0.5, 1), (0.5 + d, 0), (0.5 + 2 * d, 0)], "B")
    add(f"chain_nonevent_top_{d:.4g}", [(0.5, 1), (0.5 + d, 1), (0.5 + 2 * d, 0)], "B")
    add(f"two_two_tied_{d:.4g}", [(0.5, 0), (0.5 + d, 1), (0.2, 0), (0.8, 1)], "C")
    add(f"two_two_all_within_{d:.4g}", [(0.5, 0), (0.5 + d, 1), (0.5 + 2 * d, 0), (0.5 + 3 * d, 1)], "C")
add("one_one_distinct", [(0.4, 0), (0.6, 1)], "C")
add("one_one_distinct_wrong_way", [(0.6, 0), (0.4, 1)], "C")
add("one_one_equal", [(0.4, 0), (0.4, 1)], "C")
add("one_event_two_nonevents", [(0.98, 0), (0.9, 1), (0.54, 0)], "C")
add("one_event_three_nonevents", [(0.2, 0), (0.5, 1), (0.6, 0), (0.7, 0)], "C")
add("one_event_top_of_three", [(0.2, 0), (0.9, 1), (0.6, 0), (0.7, 0)], "C")

Path(__file__).with_name("x12_groups.json").write_text(json.dumps(groups))
print("/* X12: the standard error of the ROC area when a class has one observation. Generated by x12_make.py;")
print("   every probability is the hex of a binary64 value. */")
print("ods graphics off;")
print("data ra; input g p :hex16. y; datalines;")
for g in groups:
    for p, y in g["rows"]:
        print(g["g"], p, y)
print(""";
ods select none;
proc logistic data=ra;
  by g;
  model y(event='1') = p / nofit;
  roc 'M' pred=p;
  ods output ROCAssociation=ro;
run;
ods select all;
data _null_; set ro;
  put "X12 roc " g= Area= hex16. StdErr= hex16. LowerArea= hex16. UpperArea= hex16. SomersD= hex16. Gamma= hex16. TauA= hex16.;
run;""")
