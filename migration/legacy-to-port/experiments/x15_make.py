"""Generate x15_best32_whole.sas: up to which whole number does BEST32. print every digit? X13, X14:
6.474114781705129e31 (32 digits) prints in full, 2**106 = 8.11e31 and 9.32e31 print in E-notation.
Values either side of 2**106, 32-digit values below it, and their negatives (33 characters with the sign).
Usage: python3 x15_make.py > x15_best32_whole.sas"""

import math
import random
import struct


def hx(x: float) -> str:
    return struct.pack(">d", x).hex().upper()


rnd = random.Random(20261116)
t = 2.0**106
vals: list[float] = [t, math.nextafter(t, 0.0), math.nextafter(math.nextafter(t, 0.0), 0.0), math.nextafter(t, math.inf), 5e31, 6e31, 7e31, 7.5e31, 8e31, 8.1e31, 8.2e31, 9e31]
vals += [rnd.uniform(1e31, t) for _ in range(12)] + [rnd.uniform(t, 1e32) for _ in range(6)] + [rnd.uniform(1e30, 1e31) for _ in range(4)]
vals += [2.0**105, 2.0**104, 2.0**103, 2.0**100, 1e31, 9.999999999999999e30, 1e30, 1e29]
vals += [-v for v in vals]

print("/* X15: the largest whole number BEST32. prints in full. Generated by x15_make.py. */")
print('data _null_; input x :hex16.; put "X15 " x hex16. " [" x best32. "]"; datalines;')
for v in vals:
    print(hx(v))
print(";")
