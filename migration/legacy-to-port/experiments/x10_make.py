"""Generate x10_roc_stderr.sas: which pairs does PROC LOGISTIC's ROC statement count as equal in the
STANDARD ERROR of the area? X07 fits "DeLong components from the plain comparison of the two
probabilities, centred on the (ROCEPS-grouped) area"; fix_Q23_near then needs 0.5 and 0.5000000000001
equal but 0.300000000001 and 0.300000000005 different, so a second, smaller tolerance exists.
  A  one pair (non-event at base, event at base + d) plus two anchors, d from 1 ulp to 1e-9 at several
     bases: tied in the standard error gives sqrt(5/32), not tied gives sqrt(9/32)
  B  fix_Q23_near itself; classes of one observation; chains
Usage: python3 x10_make.py > x10_roc_stderr.sas   (x10_groups.json is written next to it)"""

import json
import math
import struct
import sys
from pathlib import Path


def hx(x: float) -> str:
    return struct.pack(">d", x).hex().upper()


groups: list[dict] = []


def add(tag: str, rows: list[tuple[float, int]], part: str) -> None:
    groups.append({"g": len(groups) + 1, "part": part, "tag": tag, "rows": [[hx(p), y] for p, y in rows]})


ANCH = [(0.9, 1), (0.95, 0)]
extra = json.loads(sys.argv[1]) if len(sys.argv) > 1 else None
if extra is None:
    for base in (0.0, 1e-6, 0.001, 0.05, 0.3, 0.5, 0.7, 0.85):
        for j in range(0, 29):
            d = 10.0 ** (-16 + j / 4)
            if base + d > base:
                add(f"abs_{base}_{d:.4g}", [(base, 0), (base + d, 1), *ANCH], "A")
        if base > 0:
            for k in (1, 2, 3, 4, 6, 8, 16, 32, 64, 128, 256, 1024, 4096, 16384, 65536):
                add(f"ulp_{base}_{k}", [(base, 0), (base + k * math.ulp(base), 1), *ANCH], "A")
else:
    for tag, rows in extra:
        add(tag, [(float.fromhex(p) if isinstance(p, str) else p, y) for p, y in rows], "A")
add("q23_near", [(0.300000000005, 1), (0.300000000001, 0), (0.300000000005, 0), (0.1, 0), (0.5, 0), (0.5000000000001, 1)], "B")
add("one_event_two_nonevents", [(0.98, 0), (0.9, 1), (0.54, 0)], "B")
add("two_events_one_nonevent", [(0.98, 1), (0.9, 0), (0.54, 1)], "B")
add("one_one_distinct", [(0.4, 0), (0.6, 1)], "B")
add("one_one_tied", [(0.4, 0), (0.4, 1)], "B")
add("two_one_all_tied", [(0.4, 1), (0.4, 0), (0.4, 1)], "B")
add("one_three", [(0.2, 0), (0.5, 1), (0.6, 0), (0.7, 0)], "B")

Path(__file__).with_name("x10_groups.json" if extra is None else "x10b_groups.json").write_text(json.dumps(groups))
print("/* X10: the equality used in the standard error of PROC LOGISTIC's ROC area. Generated by x10_make.py;")
print("   every probability is the hex of a binary64 value. */")
print("ods graphics off;")
print("data ra; input g p :hex16. y; datalines;")
for g in groups:
    for p, y in g["rows"]:
        print(g["g"], p, y)
print(""";
ods select none;
proc logistic data=ra;
  by g;
  model y(event='1') = p / nofit;
  roc 'M' pred=p;
  ods output ROCAssociation=ro;
run;
ods select all;
data _null_; set ro;
  put "X10 roc " g= Area= hex16. StdErr= hex16. LowerArea= hex16. UpperArea= hex16. SomersD= hex16. Gamma= hex16. TauA= hex16.;
run;""")
