"""Generate x11_best32.sas: what does BEST32. print for a value that needs more than 15 significant
digits? (the format of income_medians.csv; X09 printed 1234567.123456789 as 1234567.12345678).
Every value is the hex of a binary64 number; the log gives hex and BEST32. text side by side.
Usage: python3 x11_make.py > x11_best32.sas"""

import math
import random
import struct


def hx(x: float) -> str:
    return struct.pack(">d", x).hex().upper()


vals: list[float] = [12345678901234567, 1234567.123456789, 6172839450618783.5, 2499.9999999999995, 0.1, 1e15, 123456789012345678]
# medians of two incomes: (a + b) / 2 and sums of decimal fractions
vals += [(0.1 + 0.2) / 2, 0.1 + 0.2, 0.1 + 0.7, (1000.1 + 2000.2) / 2, (3333.33 + 4444.44) / 2, (2500.005 + 2500.015) / 2, 1 / 3, 2 / 3, 100 / 3, 20000 / 3, 1e7 / 3, 5400.0, 5400.5, 2500.25, 1e15 + 0.5]
vals += [0.7999999999999999, 0.30000000000000004, 0.15000000000000002, 1.0000000000000002, 0.9999999999999999, 4999.999999999999, 5000.000000000001]
rnd = random.Random(20261116)
for e in range(-8, 21):  # random 17-digit values at every magnitude
    for _ in range(8):
        vals.append(rnd.uniform(1, 10) * 10.0**e)
for e in range(0, 16):  # d digits before the point, then a run of 9s or a 5 at the 15th-17th digit
    b = float(rnd.randint(10**e, 10 ** (e + 1) - 1))
    for k in (1, 2, 3, 7):
        vals += [math.nextafter(b + 0.5, 0.0) if k == 1 else b + 0.5 - k * math.ulp(b + 0.5), b + 0.5 + k * math.ulp(b + 0.5), b + 1 - k * math.ulp(b + 1.0)]
for _ in range(60):  # incomes with cents and their half sums
    a, b = round(rnd.uniform(0, 30000), 2), round(rnd.uniform(0, 30000), 2)
    vals += [(a + b) / 2, a + b / 7]
vals += [-v for v in vals[:40]]

print("/* X11: BEST32. of values that need more than 15 significant digits. Generated by x11_make.py. */")
print('data _null_; input x :hex16.; put "X11 " x hex16. " [" x best32. "]"; datalines;')
for v in vals:
    print(hx(v))
print(";")
