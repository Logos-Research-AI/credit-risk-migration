"""Generate x14_best32_enotation.sas: where exactly does the 14-digit mantissa of BEST32.'s E-notation
step to the next digit? X13: 9.276747499544084e-200 prints '9.2767474995441E-200' and
1.999999999999995e-07 prints '1.9999999999999E-7', so the mantissa is cut after the value is raised by
a relative amount between 1.9e-15 and 2.5e-15. For five 14-digit mantissas at seven exponents: the 26
doubles just below the step and the 2 from it; then the smallest normal number and its neighbours
(X13: a subnormal prints '0'), and whole numbers of 31 to 33 digits (X13: 32 digits print in E-notation).
Usage: python3 x14_make.py > x14_best32_enotation.sas"""

import math
import random
import struct
from fractions import Fraction


def hx(x: float) -> str:
    return struct.pack(">d", x).hex().upper()


vals: list[float] = []
rnd = random.Random(20261116)
MANTS = [10**13, 2 * 10**13, 49020776365274, 75 * 10**12, 92767474995441]
for e in (-6, -9, -20, -100, -300, 32, 100):
    for m in MANTS:
        q = Fraction(m) * Fraction(10) ** (e - 13)
        v = float(q)
        while Fraction(v) < q:  # v: the smallest double at or above the step
            v = math.nextafter(v, math.inf)
        w = v
        for _ in range(2):
            vals.append(w)
            w = math.nextafter(w, math.inf)
        w = v
        for _ in range(26):
            w = math.nextafter(w, 0.0)
            vals.append(w)
tiny = 2.2250738585072014e-308
vals += [tiny, math.nextafter(tiny, 0.0), math.nextafter(tiny, 1.0), 1e-308, 2e-308, 2.2e-308, 2.3e-308, 3e-308, 1e-307, 4.4501477170144023e-308]
for d in (31, 32, 33):
    vals += [float(10 ** (d - 1)), float(rnd.randint(10 ** (d - 1), 10**d - 1)), math.nextafter(float(10**d), 0.0)]
vals += [9.999999999999999e30, 1e31, 9.9999999999999e31, 9.99999999999999e31, 1.0000000000000002e31, 2.0**103, 2.0**104, 2.0**105]

print("/* X14: the step of the 14-digit mantissa in BEST32.'s E-notation. Generated by x14_make.py. */")
print('data _null_; input x :hex16.; put "X14 " x hex16. " [" x best32. "]"; datalines;')
for v in vals:
    print(hx(v))
print(";")
