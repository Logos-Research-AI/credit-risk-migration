"""Generate x08_roceps_boundary.sas (finding P1): where exactly is the ROCEPS boundary? X07 showed a pair
(0, ROCEPS + 1 ulp) is still tied. Pairs (v, v + d) with d = fl(sqrt(2^-53)) + j ulps, d exact, at
several v; each BY group is the pair plus two anchors, so Area = 0.375 if tied and 0.5 if not.
Usage: python3 x08_make.py > x08_roceps_boundary.sas   (writes x08_groups.json)"""

import json
import math
import struct
from pathlib import Path

EPS = math.sqrt(2.0**-53)
U = math.ulp(EPS)  # 2^-79


def hx(x: float) -> str:
    return struct.pack(">d", x).hex().upper()


groups = []


def add(v: float, j: int) -> None:
    d = EPS + j * U
    top = v + d
    assert top - v == d and (top - v) - EPS == j * U, (v, j)
    groups.append({"g": len(groups) + 1, "v": hx(v), "top": hx(top), "j": j})


small = list(range(-4, 41)) + [2**k for k in range(6, 18)] + [50226, 50227, 50228]
for j in small:
    add(0.0, j)
for v in (2.0**-40, 2.0**-28, 2.0**-60):
    for j in list(range(-2, 9)) + [2**k for k in range(4, 17, 2)]:
        add(v, j)
for j in (-3, -1, 1, 3, 5, 7, 17, 65, 1025):  # next binade: d must have an even mantissa
    add(2.0**-27, j)
for v, step in ((2.0**-26, 2), (2.0**-24, 8), (2.0**-20, 128), (2.0**-10, 2**17), (0.5, 2**26), (0.86, 2**26)):
    j0 = -((int(EPS / U)) % step)  # largest d <= fl(sqrt(2^-53)) on v's grid
    for k in range(-2, 4):
        add(v, j0 + k * step)
Path(__file__).with_name("x08_groups.json").write_text(json.dumps(groups))

print("/* X08 (finding P1): the exact ROCEPS boundary. Generated by x08_make.py. */")
print("ods graphics off;")
print("data rb; input g p :hex16. y; datalines;")
for g in groups:
    print(g["g"], g["v"], 0)
    print(g["g"], g["top"], 1)
    print(g["g"], hx(0.9), 1)
    print(g["g"], hx(0.95), 0)
print(""";
ods select none;
proc logistic data=rb;
  by g;
  model y(event='1') = p / nofit;
  roc 'M' pred=p;
  ods output ROCAssociation=rbo;
run;
ods select all;
data _null_; set rbo; put "X08 roc " g= Area=; run;""")
